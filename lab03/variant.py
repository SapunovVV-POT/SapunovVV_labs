num=int(input("Введите прогресс выполенения учебного плана: "))
if (0<=num<=39):
    print("Прогресс выполнения находится в начале")
elif (40<=num<=99):
    print("Выполнение находится в процессе")
elif (num>100 or num<0):
        print("Ошибка диапозона")
else:
    print("Учебный план выполнен")
